def escape_cell(value: Any) -> str:
    if value is None:
        return "-"
    return str(value).replace("|", "\\|").replace("\n", " ").strip() or "-"


def default_description(column) -> str:
    default = column.default
    if default is None:
        default = column.server_default
    if default is None:
        return "-"
    value = getattr(default, "arg", default)
    if callable(value):
        return getattr(value, "__name__", "generated")
    return str(value)


def index_predicate(index) -> str | None:
    for dialect in ("postgresql", "sqlite"):
        options = index.dialect_options.get(dialect)
        if options and options.get("where") is not None:
            return str(options.get("where"))
    return None


def generate_database_reference() -> None:
    lines = [
        "# Database Reference",
        "",
        "> Generated from `Base.metadata` by `scripts/generate_code_reference_docs.py`.",
        "> Application-level workflow validation is documented in",
        "> [Modules and Workflows](06_MODULES_AND_WORKFLOWS.md).",
        "",
        "## Conventions",
        "",
        "All primary keys are 36-character UUID strings generated by the application.",
        "Most records inherit `created_at` and `updated_at` from `BaseModel`.",
        "`facility_id` is the immutable tenant identifier where present;",
        "`facility_slug` remains for routing and compatibility. Nullable in this",
        "reference means the database column permits null; route validation may be stricter.",
        "",
        "## Entity Relationship Diagram",
        "",
        "```mermaid",
        "erDiagram",
    ]

    relationships: set[tuple[str, str, str]] = set()
    for table in Base.metadata.sorted_tables:
        for foreign_key in table.foreign_keys:
            relationships.add(
                (
                    foreign_key.column.table.name,
                    table.name,
                    foreign_key.parent.name,
                )
            )
    for parent, child, label in sorted(relationships):
        lines.append(f'    {parent} ||--o{{ {child} : "{label}"')
    lines.extend(["```", "", "## Tables", ""])

    for table in sorted(Base.metadata.tables.values(), key=lambda item: item.name):
        lines.extend(
            [
                f"### `{table.name}`",
                "",
                TABLE_PURPOSES.get(
                    table.name,
                    "Persistence table registered by the HIS.Pro SQLAlchemy model layer.",
                ),
                "",
                "| Field | Type | Null | Key / relationship | Default |",
                "|---|---|---:|---|---|",
            ]
        )
        for column in table.columns:
            flags: list[str] = []
            if column.primary_key:
                flags.append("PK")
            if column.unique:
                flags.append("UNIQUE")
            for foreign_key in column.foreign_keys:
                flags.append(f"FK -> `{foreign_key.target_fullname}`")
            lines.append(
                "| `{}` | `{}` | {} | {} | {} |".format(
                    escape_cell(column.name),
                    escape_cell(column.type),
                    "yes" if column.nullable else "no",
                    escape_cell(", ".join(flags)),
                    escape_cell(default_description(column)),
                )
            )

        lines.extend(["", "**Indexes and constraints**", ""])
        constraint_lines: list[str] = []
        for index in sorted(table.indexes, key=lambda item: item.name or ""):
            columns = ", ".join(f"`{column.name}`" for column in index.columns)
            qualifier = "unique " if index.unique else ""
            predicate = index_predicate(index)
            suffix = f" where `{predicate}`" if predicate else ""
            constraint_lines.append(
                f"- `{index.name}`: {qualifier}index on {columns}{suffix}."
            )
        for constraint in table.constraints:
            if isinstance(constraint, UniqueConstraint):
                columns = ", ".join(
                    f"`{column.name}`" for column in constraint.columns
                )
                name = constraint.name or "unnamed unique constraint"
                constraint_lines.append(f"- `{name}`: unique across {columns}.")
        lines.extend(constraint_lines or ["- No additional model-declared indexes."])

        foreign_keys = sorted(
            (
                foreign_key.parent.name,
                foreign_key.target_fullname,
            )
            for foreign_key in table.foreign_keys
        )
        if foreign_keys:
            lines.extend(["", "**Relationships**", ""])
            lines.extend(
                f"- `{source}` references `{target}`."
                for source, target in foreign_keys
            )

        required_fields = [
            column.name
            for column in table.columns
            if not column.nullable
            and not column.primary_key
            and column.default is None
            and column.server_default is None
        ]
        lines.extend(["", "**Database-enforced validation**", ""])
        if required_fields:
            lines.append(
                "- Required on insert: "
                + ", ".join(f"`{field}`" for field in required_fields)
                + "."
            )
        else:
            lines.append("- No additional required fields beyond the primary key.")
        lines.append(
            "- String lengths, foreign keys, unique indexes, and nullability are enforced as listed above."
        )
        lines.append("")

    lines.extend(
        [
            "## Implementation Notes",
            "",
            "- `insurance_providers` and `insurance_claims` do not contain tenant columns.",
            "  They are retained legacy models and must not be exposed to tenant traffic",
            "  until composite application/tenant isolation is added.",
            "- Several legacy tables retain both `facility_id` and `facility_slug`.",
            "  New authorization decisions should use the immutable facility UUID and",
            "  keep slug handling at the routing boundary.",
            "- `pharmacy_inventory` is one row per medication and therefore represents",
            "  facility-level stock, not independent branch or batch ledgers.",
            "- Ward beds are facility-level resources. Branch-scoped users are prevented",
            "  from assigning those beds until branch ownership is modeled.",
            "",
        ]
    )
    DATABASE_OUTPUT.write_text("\n".join(lines), encoding="utf-8")


def dependency_access(route: APIRoute) -> tuple[bool, list[str]]:
    roles: set[str] = set()
    authenticated = False

    def visit(dependant) -> None:
        nonlocal authenticated
        for dependency in dependant.dependencies:
            call = dependency.call
            name = getattr(call, "__name__", "")
            module = getattr(call, "__module__", "")
            if name in {"get_current_user", "dependency"} and (
                "dependencies" in module or name == "dependency"
            ):
                authenticated = True
            closure = getattr(call, "__closure__", None) or []
            for cell in closure:
                value = cell.cell_contents
                if isinstance(value, tuple) and value and all(
                    isinstance(item, str) for item in value
                ):
                    roles.update(value)
                    authenticated = True
            visit(dependency)

    visit(route.dependant)
    if route.path in PUBLIC_PATHS:
        authenticated = False
        roles.clear()
    return authenticated, sorted(roles)


def schema_name(schema: Any) -> str:
    if not schema:
        return "Not declared"
    if "$ref" in schema:
        return f"`{schema['$ref'].split('/')[-1]}`"
    if schema.get("type") == "array":
        return f"Array of {schema_name(schema.get('items', {}))}"
    if "anyOf" in schema:
        return " or ".join(schema_name(item) for item in schema["anyOf"])
    return f"`{schema.get('type', 'object')}`"


def resolve_schema(schema: Any, components: dict[str, Any]) -> Any:
    if not isinstance(schema, dict):
        return schema
    if "$ref" in schema:
        return components.get(schema["$ref"].split("/")[-1], {})
    return schema


def example_value(
    schema: Any,
    components: dict[str, Any],
    *,
    field_name: str = "value",
    depth: int = 0,
) -> Any:
    if depth > 4:
        return None
    schema = resolve_schema(schema or {}, components)
    if "example" in schema:
        return schema["example"]
    if "default" in schema:
        return schema["default"]
    if schema.get("enum"):
        return schema["enum"][0]
    if "anyOf" in schema:
        non_null = [
            item for item in schema["anyOf"] if item.get("type") != "null"
        ]
        return example_value(
            non_null[0] if non_null else {},
            components,
            field_name=field_name,
            depth=depth + 1,
        )
    schema_type = schema.get("type")
    if schema_type == "array":
        return [
            example_value(
                schema.get("items", {}),
                components,
                field_name=field_name,
                depth=depth + 1,
            )
        ]
    if schema_type == "object" or schema.get("properties"):
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        selected = [
            name
            for name in properties
            if name in required or len(properties) <= 8
        ][:12]
        return {
            name: example_value(
                properties[name],
                components,
                field_name=name,
                depth=depth + 1,
            )
            for name in selected
        }
    if schema_type == "integer":
        return max(int(schema.get("minimum", 1)), 1)
    if schema_type == "number":
        return max(float(schema.get("minimum", 1)), 1.0)
    if schema_type == "boolean":
        return True
    if schema.get("format") == "date":
        return "2026-07-31"
    if schema.get("format") == "date-time":
        return "2026-07-31T09:00:00Z"
    if schema.get("format") == "email":
        return "staff@example.invalid"
    lower_name = field_name.lower()
    if lower_name.endswith("_id") or lower_name == "id":
        return "00000000-0000-0000-0000-000000000000"
    if "phone" in lower_name:
        return "+2348000000000"
    if "slug" in lower_name:
        return "example-hospital"
    if "password" in lower_name:
        return "<strong-password>"
    if "date" in lower_name:
        return "2026-07-31"
    return f"<{field_name}>"


def request_schema(operation: dict[str, Any]) -> tuple[str | None, dict[str, Any] | None]:
    request_body = operation.get("requestBody", {})
    content = request_body.get("content", {})
    for content_type in (
        "application/json",
        "multipart/form-data",
        "application/x-www-form-urlencoded",
    ):
        if content_type in content:
            return content_type, content[content_type].get("schema", {})
    if content:
        content_type, value = next(iter(content.items()))
        return content_type, value.get("schema", {})
    return None, None


def response_schema(operation: dict[str, Any]) -> tuple[str, dict[str, Any] | None]:
    responses = operation.get("responses", {})
    success_codes = sorted(
        code for code in responses if str(code).startswith("2")
    )
    if not success_codes:
        return "-", None
    code = success_codes[0]
    content = responses[code].get("content", {})
    if "application/json" in content:
        return str(code), content["application/json"].get("schema", {})
    return str(code), None


def curl_example(
    method: str,
    path: str,
    authenticated: bool,
    has_body: bool,
    body_example: Any,
) -> str:
    command = [f"curl -X {method}", f'"https://<tenant>.app.his.pro{path}"']
    if authenticated:
        command.append('-H "Authorization: Bearer <access-token>"')
    if method in {"POST", "PUT", "PATCH", "DELETE"}:
        command.append('-H "Idempotency-Key: <unique-operation-key>"')
    if has_body:
        command.append('-H "Content-Type: application/json"')
        serialized = json.dumps(body_example, separators=(",", ":"))
        command.append(f"--data '{serialized}'")
    return " \\\n  ".join(command)


def route_group(route: APIRoute) -> str:
    if route.tags:
        return str(route.tags[0]).replace("-", " ").title()
    if route.path == "/health":
        return "Operations"
    parts = [part for part in route.path.split("/") if part]
    return (parts[2] if len(parts) > 2 else parts[-1]).replace("-", " ").title()


def source_notes(route: APIRoute) -> list[str]:
    try:
        source = inspect.getsource(route.endpoint)
    except (OSError, TypeError):
        return []
    notes = []
    if "require_idempotency_key" in source or "WriteIdempotencyService.claim" in source:
        notes.append("A valid `Idempotency-Key` is required and replays are tenant-scoped.")
    if "apply_branch_filter" in source or "ensure_patient_branch_access" in source:
        notes.append("Branch access is constrained by the authenticated user's scope.")
    if "with_for_update" in source:
        notes.append("The mutation uses a database row lock on supported databases.")
    return notes


def generate_api_reference() -> None:
    specification = app.openapi()
    components = specification.get("components", {}).get("schemas", {})
    grouped: dict[str, list[tuple[APIRoute, str, dict[str, Any]]]] = defaultdict(list)

    for route in app.routes:
        if not isinstance(route, APIRoute) or not route.include_in_schema:
            continue
        path_item = specification.get("paths", {}).get(route.path, {})
        for method in sorted(route.methods or []):
            if method in {"HEAD", "OPTIONS"}:
                continue
            operation = path_item.get(method.lower())
            if operation:
                grouped[route_group(route)].append((route, method, operation))

    lines = [
        "# API Reference",
        "",
        "> Generated from the registered FastAPI routes and OpenAPI schemas by",
        "> `scripts/generate_code_reference_docs.py`. Example values are illustrative;",
        "> schemas and access requirements come from the running application.",
        "",
        "## Protocol Conventions",
        "",
        "- Base path: `/api/v1` except `/health`.",
        "- Authentication: bearer access token or the secure access-token cookie.",
        "- Browser cookie mutations also require the double-submit CSRF header.",
        "- Mutation clients should send one stable `Idempotency-Key` per user action.",
        "- Validation errors use HTTP `422`; business validation generally uses `400`.",
        "- Tenant or branch mismatches generally return `404` to avoid record disclosure.",
        "- Rate limiting may return `429`; unexpected failures use the normalized error envelope.",
        "",
        "## Error Envelope",
        "",
        "```json",
        '{"error":{"message":"Request could not be completed","code":400,"status":400}}',
        "```",
        "",
        "## Endpoints",
        "",
    ]

    for group in sorted(grouped):
        lines.extend([f"## {group}", ""])
        routes = sorted(grouped[group], key=lambda item: (item[0].path, item[1]))
        for route, method, operation in routes:
            authenticated, roles = dependency_access(route)
            content_type, body_schema = request_schema(operation)
            success_code, success_schema = response_schema(operation)
            summary = operation.get("summary") or route.name.replace("_", " ").title()
            description = operation.get("description") or "No additional route description is declared."

            lines.extend(
                [
                    f"### `{method} {route.path}`",
                    "",
                    f"**Purpose:** {summary}. {description}",
                    "",
                    "**Access:** "
                    + (
                        "Public."
                        if not authenticated
                        else (
                            "Authenticated; roles: "
                            + ", ".join(f"`{role}`" for role in roles)
                            + "."
                            if roles
                            else "Authenticated user."
                        )
                    ),
                    "",
                ]
            )

            parameters = operation.get("parameters", [])
            if parameters:
                lines.extend(
                    [
                        "**Parameters**",
                        "",
                        "| Name | In | Required | Schema |",
                        "|---|---|---:|---|",
                    ]
                )
                for parameter in parameters:
                    lines.append(
                        "| `{}` | {} | {} | {} |".format(
                            escape_cell(parameter.get("name")),
                            escape_cell(parameter.get("in")),
                            "yes" if parameter.get("required") else "no",
                            escape_cell(schema_name(parameter.get("schema", {}))),
                        )
                    )
                lines.append("")

            if body_schema is not None:
                lines.extend(
                    [
                        f"**Request body:** `{content_type}` using {schema_name(body_schema)}.",
                        "",
                    ]
                )
            else:
                lines.extend(["**Request body:** none.", ""])

            lines.extend(
                [
                    f"**Success:** HTTP `{success_code}`; response schema {schema_name(success_schema)}.",
                    "",
                    "**Possible errors:** `400` business validation, "
                    + ("`401` authentication, `403` authorization, " if authenticated else "")
                    + ("`404` missing or inaccessible resource, " if "{" in route.path else "")
                    + "`409` idempotency/state conflict where applicable, `422` schema validation, `429` rate limit.",
                    "",
                ]
            )
            for note in source_notes(route):
                lines.extend([f"- {note}", ""])

            body_example = (
                example_value(body_schema, components) if body_schema is not None else None
            )
            lines.extend(
                [
                    "**Example request**",
                    "",
                    "```bash",
                    curl_example(
                        method,
                        route.path,
                        authenticated,
                        body_schema is not None and content_type == "application/json",
                        body_example,
                    ),
                    "```",
                    "",
                ]
            )
            if success_schema:
                lines.extend(
                    [
                        "**Example response shape**",
                        "",
                        "```json",
                        json.dumps(
                            example_value(success_schema, components),
                            indent=2,
                            ensure_ascii=True,
                        ),
                        "```",
                        "",
                    ]
                )
            else:
                lines.extend(
                    [
                        "**Example response shape:** not constrained by a declared JSON response model.",
                        "",
                    ]
                )

    lines.extend(
        [
            "## Implementation Notes",
            "",
            "- FastAPI documentation routes are disabled in production, but the OpenAPI",
            "  document remains registered at `/api/v1/openapi.json` in the current app.",
            "  Restrict it at the edge if public schema discovery is not desired.",
            "- Authentication is implemented through route dependencies plus JWT/session",
            "  middleware, so OpenAPI does not currently expose a standard security scheme.",
            "- Several endpoints return a bare array while accepting pagination inputs;",
            "  callers do not receive total-count metadata.",
            "",
        ]
    )
    API_OUTPUT.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    generate_database_reference()
    generate_api_reference()
    print(f"Generated {DATABASE_OUTPUT.relative_to(ROOT)}")
    print(f"Generated {API_OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
